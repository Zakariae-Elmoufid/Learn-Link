package org.example.learnlink.modules.matching.entity.enums;

/**
 * Enum representing the status of a study group.
 */
public enum GroupStatus {
    /**
     * Group is active and accepting new members
     */
    ACTIVE,

    /**
     * Group is full and not accepting new members
     */
    FULL,

    /**
     * Group has been archived
     */
    ARCHIVED,

    /**
     * Group has been deleted/disbanded
     */
    DISBANDED
}
