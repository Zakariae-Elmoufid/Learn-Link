package org.example.learnlink.modules.matching.entity.enums;

/**
 * Enum representing the role of a member within a study group.
 */
public enum GroupRole {
    /**
     * Group creator with full administrative privileges
     */
    OWNER,

    /**
     * Administrator with management capabilities
     */
    ADMIN,

    /**
     * Regular group member
     */
    MEMBER
}
